# ---- Ghép chuỗi tránh literal đóng tag trong nguồn test ---- 
AK = "<arg_key>"
KV = "<arg_value>"
EK = "</" + "arg_key>"
EV = "</" + "arg_value>"
CT = "</" + "tool_call>"


def xcall(opener: str, *pairs) -> str:
    body = "".join(AK + str(k) + EK + KV + str(v) + EV for k, v in pairs)
    return "<tool_call" + opener + ">" + body + CT


def fenced(payload: str) -> str:
    return "```luas30-tool\n" + payload + "\n```"


