def handle_changes(payload):
    """Sương năng y nhu MainWindow._prepare/_apply trong che do edit_auto."""
    data = payload if isinstance(payload, dict) else {"edits": payload}
    try:
        cs = change_service.prepare(project, data.get("edits") or [])
    except Exception as exc:
        chat.on_code_changes_failed(str(exc))
        return
    chat.on_code_changes_prepared(cs.summary())
    if bool(data.get("auto_apply")):
        applied, backup = change_service.apply(cs)
        files = [{"path": c.relative_path, "added": c.added_lines,
                  "removed": c.removed_lines} for c in cs.changes]
        applied_log.extend(c.relative_path for c in cs.changes)
        chat.on_code_changes_applied(
            [str(p) for p in applied], str(backup or ""), files=files)


chat.changes_proposed.connect(handle_changes)
chat.review_changes_requested.connect(lambda: None)

