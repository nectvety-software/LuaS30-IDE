class FakeThread(QThread):
    completed = Signal(str)
    failed = Signal(str)
    idx = 0
    prompts: list[str] = []

    def __init__(self, cfg, api_key, system_prompt, messages, parent=None):
        super().__init__(parent)
        self.messages = list(messages or [])

    def run(self):
        if self.isInterruptionRequested():
            return
        i = FakeThread.idx
        FakeThread.idx += 1
        FakeThread.prompts.append(str(self.messages[-1]["content"])[:400] if self.messages else "")
        if i >= len(SCRIPT):
            self.failed.emit("E2E script het luot tra loi (agent van muon goi them)")
            return
        self.completed.emit(SCRIPT[i])


